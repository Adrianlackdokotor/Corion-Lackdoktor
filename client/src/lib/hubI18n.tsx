type Ctx = {
  lang: HubLang;
  setLang: (l: HubLang) => void;
  t: (key: string) => string;
};

const HubI18nContext = createContext<Ctx | null>(null);
const STORAGE_KEY = "hubplus.lang";

export function HubI18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<HubLang>(() => {
    if (typeof window === "undefined") return "de";
    const saved = window.localStorage.getItem(STORAGE_KEY) as HubLang | null;
    return saved && ["de", "ro", "en"].includes(saved) ? saved : "de";
  });

  useEffect(() => {
    if (typeof window !== "undefined") {
      window.localStorage.setItem(STORAGE_KEY, lang);
    }
  }, [lang]);

  const setLang = (l: HubLang) => setLangState(l);
  const t = (key: string) => CATALOG[lang][key] ?? CATALOG.de[key] ?? key;

  return (
    <HubI18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </HubI18nContext.Provider>
  );
}

export function useHubI18n(): Ctx {
  const ctx = useContext(HubI18nContext);
  if (!ctx) {
    return {
      lang: "de",
      setLang: () => {},
      t: (k: string) => CATALOG.de[k] ?? k,
    };
  }
  return ctx;
}
